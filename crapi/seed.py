"""Create the disposable test accounts and one order each in a LOCAL crAPI.

    python crapi/seed.py

Safe to run again: it reuses accounts and orders that still work.

It refuses to run against anything but this machine, because it creates
accounts. Writes (both gitignored, never committed):

  crapi/.env.local   the generated passwords
  crapi/state.json   the order ids (which user owns which order)

Stdlib only, so it needs nothing installed.
"""
from __future__ import annotations

import json
import secrets
import sys
import urllib.error
import urllib.request
from pathlib import Path
from urllib.parse import urlsplit

HERE = Path(__file__).parent
ENV_FILE = HERE / ".env.local"
STATE_FILE = HERE / "state.json"

BASE = "http://127.0.0.1:8888"
USERS = ("user_A", "user_B")


def call(method: str, path: str, body: dict | None = None, token: str | None = None):
    headers = {"Content-Type": "application/json"}
    if token:
        headers["Authorization"] = "Bearer " + token
    request = urllib.request.Request(
        BASE + path, method=method, headers=headers,
        data=json.dumps(body).encode() if body is not None else None)
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            raw, status = response.read(), response.status
    except urllib.error.HTTPError as error:
        raw, status = error.read(), error.code
    try:
        return status, json.loads(raw)
    except ValueError:
        return status, raw.decode("utf-8", "replace")


def load_env() -> dict:
    values = {}
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text().splitlines():
            if "=" in line and not line.startswith("#"):
                key, value = line.split("=", 1)
                values[key] = value
    return values


def save_env(values: dict) -> None:
    lines = ["# generated by crapi/seed.py: local test accounts, not real credentials. Never commit."]
    lines += [f"{key}={value}" for key, value in values.items()]
    ENV_FILE.write_text("\n".join(lines) + "\n")


def login(email: str, password: str) -> str | None:
    status, data = call("POST", "/identity/api/auth/login", {"email": email, "password": password})
    return data.get("token") if status == 200 and isinstance(data, dict) else None


def main() -> int:
    if urlsplit(BASE).hostname not in {"127.0.0.1", "localhost"}:
        print("refusing: this script creates accounts and only runs against a local crAPI")
        return 2

    status, _ = call("GET", "/")
    if status != 200:
        print(f"crAPI is not answering on {BASE} (got {status}). Start it first: see crapi/README.md")
        return 1

    env = load_env()
    state = json.loads(STATE_FILE.read_text()) if STATE_FILE.exists() else {}
    state.setdefault("orders", {})

    for index, user in enumerate(USERS):
        email_key, password_key = f"{user.upper()}_EMAIL", f"{user.upper()}_PASSWORD"
        if email_key not in env:
            env[email_key] = f"harness.{user.lower()}.{secrets.token_hex(3)}@example.com"
            env[password_key] = "Aa1!" + secrets.token_urlsafe(12)
            save_env(env)

        token = login(env[email_key], env[password_key])
        if token is None:
            status, data = call("POST", "/identity/api/auth/signup", {
                "name": f"Harness {user}", "email": env[email_key], "number": f"90000000{index:02d}",
                "password": env[password_key]})
            if status not in (200, 201):
                print(f"signup failed for {user}: {status} {data}")
                return 1
            token = login(env[email_key], env[password_key])
        if token is None:
            print(f"could not log in as {user}")
            return 1

        order_id = state["orders"].get(user)
        if order_id is not None:
            status, _ = call("GET", f"/workshop/api/shop/orders/{order_id}", token=token)
            if status != 200:
                order_id = None
        if order_id is None:
            status, data = call("POST", "/workshop/api/shop/orders", {"product_id": 1, "quantity": 1}, token=token)
            if status not in (200, 201) or not isinstance(data, dict) or "id" not in data:
                print(f"could not create an order for {user}: {status} {data}")
                return 1
            order_id = data["id"]
            state["orders"][user] = order_id
        print(f"{user}: account ready, owns order {order_id}")

    STATE_FILE.write_text(json.dumps(state, indent=2) + "\n")
    print(f"saved {ENV_FILE.name} and {STATE_FILE.name} in {HERE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
